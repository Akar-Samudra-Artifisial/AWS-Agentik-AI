#!/usr/bin/env bash
# Stage a self-contained AgentCore direct_code_deploy bundle in build/agentcore/:
#   main.py (entrypoint) + agent/ package (with _vendor) + requirements.txt.
# The agent package uses absolute/relative imports of ``agent.*``, so it must sit
# under a parent directory instead of being the deploy root itself.
# build/ is gitignored, including the generated .bedrock_agentcore.yaml.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STAGE="$ROOT/build/agentcore"

bash "$ROOT/scripts/build_agent.sh"

mkdir -p "$STAGE"
rm -rf "$STAGE/agent"
rsync -a --exclude '.venv' --exclude '__pycache__' --exclude 'eval' \
    "$ROOT/agent/" "$STAGE/agent/"
cp "$ROOT/agent/requirements.txt" "$STAGE/requirements.txt"
cat > "$STAGE/main.py" <<'EOF'
"""AgentCore Runtime entrypoint wrapper (generated by scripts/stage_agentcore.sh)."""

from agent.app import app

if __name__ == "__main__":
    app.run()
EOF

echo "staged AgentCore bundle in $STAGE"
